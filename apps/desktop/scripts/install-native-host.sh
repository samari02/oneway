#!/bin/bash

# Install Native Messaging Host for Chrome Extension
#
# Chrome launches the host with NO argv — but Clarity only enters native-host mode
# when given --native-host. This script writes a small runner that adds that flag.
#
# Usage:
#   ./install-native-host.sh <extension_id> [<extension_id2> ...] [--] [path_to_clarity_binary]
#
# Multiple IDs: daily unpacked profile + legacy dev profile (Chrome policy may pin a stable ID later).
#
# Known Clarity extension IDs:
#   Stable (manifest `key`): bladnadefjcnkapbdclfjpbekhmmoojb
#   Legacy (pre-key unpack): pjdboibemcgajdjnppgfnffmajcokbmf
#   Legacy (dev):            pocdhgbmmooabipboifieikkigmaanok
#   Re-run this script whenever the ID changes (e.g. new manifest `key` / PEM).
#
# Dev example (after `cargo build` or `pnpm dev` once):
#   ./install-native-host.sh bladnadefjcnkapbdclfjpbekhmmoojb ./src-tauri/target/debug/appsdesktop
#   # or multiple IDs (e.g. during migration):
#   ./install-native-host.sh bladnadefjcnkapbdclfjpbekhmmoojb pjdboibemcgajdjnppgfnffmajcokbmf -- ./src-tauri/target/debug/appsdesktop

set -e

EXTENSION_IDS=()
APP_PATH="/Applications/Clarity.app/Contents/MacOS/appsdesktop"

# Chromium-family browsers that read the same manifest format (macOS).
NMH_BASE_DIRS=(
  "$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
  "$HOME/Library/Application Support/Chromium/NativeMessagingHosts"
  "$HOME/Library/Application Support/BraveSoftware/Brave-Browser/NativeMessagingHosts"
  "$HOME/Library/Application Support/Microsoft Edge/NativeMessagingHosts"
)

while [[ $# -gt 0 ]]; do
  case "$1" in
    --)
      shift
      if [[ $# -gt 0 ]]; then
        APP_PATH="$1"
      fi
      break
      ;;
    *)
      if [[ "$1" == /* ]] || [[ "$1" == *".app"* ]] || [[ -f "$1" ]]; then
        APP_PATH="$1"
        break
      fi
      EXTENSION_IDS+=("$1")
      shift
      ;;
  esac
done

CLARITY_CONFIG_DIR="$HOME/.clarity"
RUNNER_PATH="$CLARITY_CONFIG_DIR/clarity-native-host-runner.sh"

mkdir -p "$CLARITY_CONFIG_DIR"
for dir in "${NMH_BASE_DIRS[@]}"; do
  mkdir -p "$dir"
done

if [[ ${#EXTENSION_IDS[@]} -eq 0 ]]; then
    echo "⚠️  Warning: No extension ID provided."
    echo "   Usage: $0 <extension_id> [<extension_id2> ...] [--] [app_path]"
    echo ""
    echo "   You can find the extension ID at chrome://extensions"
    echo "   (Enable Developer mode to see the ID)"
    echo ""
    echo "   Using placeholder for now. You'll need to update the manifest later."
    EXTENSION_IDS=("YOUR_EXTENSION_ID_HERE")
fi

# Resolve to absolute path (required by Chrome manifest)
if [[ "$APP_PATH" != /* ]]; then
    APP_PATH="$(cd "$(dirname "$APP_PATH")" 2>/dev/null && pwd)/$(basename "$APP_PATH")" || true
fi

if [ ! -f "$APP_PATH" ] || [ ! -x "$APP_PATH" ]; then
    echo "⚠️  Warning: Binary not found or not executable: $APP_PATH"
    echo "   Build it first (e.g. pnpm dev / cargo build in apps/desktop/src-tauri)."
fi

# Runner script: Chrome invokes this; it must pass --native-host to the real binary.
cat > "$RUNNER_PATH" << EOF
#!/bin/bash
# Auto-generated by install-native-host.sh — do not edit by hand
exec "$APP_PATH" --native-host
EOF
chmod +x "$RUNNER_PATH"

MANIFEST_FILE="$(mktemp)"
trap 'rm -f "$MANIFEST_FILE"' EXIT

# Manifest points at the RUNNER, not the .app binary directly
{
  echo '{'
  echo '  "name": "com.clarity.app",'
  echo '  "description": "Clarity Desktop App - Native Messaging Host for Chrome Extension",'
  echo "  \"path\": \"$RUNNER_PATH\","
  echo '  "type": "stdio",'
  echo '  "allowed_origins": ['
  last_idx=$((${#EXTENSION_IDS[@]} - 1))
  for i in "${!EXTENSION_IDS[@]}"; do
  id="${EXTENSION_IDS[$i]}"
  comma=","
  [[ "$i" -eq "$last_idx" ]] && comma=""
  echo "    \"chrome-extension://${id}/\"${comma}"
  done
  echo '  ]'
  echo '}'
} > "$MANIFEST_FILE"

MANIFEST_PATHS=()
for dir in "${NMH_BASE_DIRS[@]}"; do
  dest="$dir/com.clarity.app.json"
  cp "$MANIFEST_FILE" "$dest"
  MANIFEST_PATHS+=("$dest")
done

echo "✅ Native messaging runner installed"
echo "   Runner: $RUNNER_PATH"
echo "   → exec: $APP_PATH"
echo ""
echo "✅ Manifest installed (${#MANIFEST_PATHS[@]} browser(s)):"
for p in "${MANIFEST_PATHS[@]}"; do
  echo "   $p"
done
echo "   Extension IDs: ${EXTENSION_IDS[*]}"
echo ""
echo "📋 Manifest contents:"
cat "$MANIFEST_FILE"
echo ""
echo ""
echo "🔧 Next steps:"
echo "   1. If you used a placeholder extension ID, re-run with real ID(s)"
echo "   2. Optional: apps/desktop/scripts/apply-chrome-managed-policy.sh apply --extension-id <ID>"
echo "   3. Reload the extension in chrome://extensions"
echo "   4. Heartbeats should appear in ~/.clarity/extension-status.json within ~1 min"